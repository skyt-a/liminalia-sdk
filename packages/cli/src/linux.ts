/**
 * Linux 版に添える起動用の sh と .desktop（lim build linux）。
 *
 * Chromium の sandbox は、権限の無い利用者の名前空間（user namespaces）か、root の持ち物で setuid の chrome-sandbox が要る。
 * tar.gz を展開しただけでは chrome-sandbox は root の持ち物にならず、Ubuntu 24.04 以降は AppArmor で名前空間を止めているので、
 * そのままでは起動できない（"The SUID sandbox helper binary was found, but is not configured correctly"）。
 * 起動用の sh は、どちらも使えないときだけ --no-sandbox を付けて起動する（LIMINALIA_SANDBOX=1 で付けない、0 で必ず付ける）。
 *
 * .desktop は、展開したフォルダから開けるように、自分の場所（%k）から sh を探す形で入れておき、sh が起動するたびに
 * 今の場所（絶対パス）の Exec と Icon に書き直す（メニューに入れるときは、起動したあとに ~/.local/share/applications へ写す）。
 * sh の中は英数字だけにする（どの言語の環境でも読めるように）。
 */

/** 起動用の sh の名前（実行ファイルの名前.sh）。 */
export const linuxLauncherName = (exe: string): string => `${exe}.sh`;

/** sh の一つの引数として書く（'…' で囲み、中の ' は '\'' にする）。 */
const shQuote = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;

/** 起動用の sh。exe は実行ファイル、desktop は .desktop、icon はアイコン（無ければ null）のファイル名（同じフォルダ）。 */
export function linuxLauncher(o: { exe: string; desktop: string; icon: string | null }): string {
  return `#!/bin/sh
# Starts the game (generated by Liminalia: lim build linux).
# Chromium's sandbox needs unprivileged user namespaces, or chrome-sandbox owned by root with the setuid bit.
# When neither is available (Ubuntu 24.04 and later restrict user namespaces with AppArmor, and extracting the
# archive does not make chrome-sandbox owned by root), the game is started with --no-sandbox.
# LIMINALIA_SANDBOX=1 never adds --no-sandbox, and LIMINALIA_SANDBOX=0 always adds it.
here=$(cd "$(dirname "$0")" && pwd)
exe="$here/"${shQuote(o.exe)}
desktop="$here/"${shQuote(o.desktop)}
icon=${o.icon ? `"$here/"${shQuote(o.icon)}` : '""'}

suid_sandbox_ok() {
  [ -u "$here/chrome-sandbox" ] && [ "$(stat -c %u "$here/chrome-sandbox" 2>/dev/null)" = "0" ]
}

userns_ok() {
  [ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = "1" ] && return 1
  [ "$(cat /proc/sys/kernel/unprivileged_userns_clone 2>/dev/null)" = "0" ] && return 1
  [ "$(cat /proc/sys/user/max_user_namespaces 2>/dev/null)" = "0" ] && return 1
  if command -v unshare >/dev/null 2>&1; then
    unshare --user --map-root-user true >/dev/null 2>&1 || return 1
  fi
  return 0
}

# Keep the .desktop file next to this script pointing at the current location (absolute paths).
desktop_escape() {
  printf '%s' "$1" | sed -e 's/\\\\/\\\\\\\\\\\\\\\\/g' -e 's/["\`$]/\\\\\\\\&/g' -e 's/%/%%/g'
}
if [ -f "$desktop" ] && [ -w "$here" ]; then
  exec_line="Exec=\\"$(desktop_escape "$here/$(basename "$0")")\\""
  icon_line=""
  [ -n "$icon" ] && icon_line="Icon=$(printf '%s' "$icon" | sed -e 's/\\\\/\\\\\\\\/g')"
  if ! grep -qxF "$exec_line" "$desktop" || { [ -n "$icon_line" ] && ! grep -qxF "$icon_line" "$desktop"; }; then
    {
      grep -v -e '^Exec=' -e '^Icon=' -e '^TryExec=' "$desktop"
      printf '%s\\n' "$exec_line"
      [ -n "$icon_line" ] && printf '%s\\n' "$icon_line"
    } > "$desktop.tmp" 2>/dev/null && chmod 755 "$desktop.tmp" 2>/dev/null && mv -f "$desktop.tmp" "$desktop" 2>/dev/null
    rm -f "$desktop.tmp" 2>/dev/null
  fi
fi

case "$LIMINALIA_SANDBOX" in
  1) exec "$exe" "$@" ;;
  0) exec "$exe" --no-sandbox "$@" ;;
esac
if suid_sandbox_ok || userns_ok; then
  exec "$exe" "$@"
fi
exec "$exe" --no-sandbox "$@"
`;
}

/** .desktop の文字列の値（\\ と改行を書き換える）。 */
const desktopString = (s: string): string => s.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/\r/g, "\\r").replace(/\t/g, "\\t");

/**
 * .desktop。Exec は自分の場所（%k）から起動用の sh を探す（展開したフォルダから開くとき）。起動用の sh が、起動するたびに
 * 絶対パスの Exec と Icon に書き直す。
 */
export function linuxDesktopEntry(o: { title: string; launcher: string; comment?: string }): string {
  const script = `exec "$(dirname "$1")/${shDoubleQuoted(o.launcher)}"`;
  return [
    "[Desktop Entry]",
    "Type=Application",
    `Name=${desktopString(o.title)}`,
    ...(o.comment ? [`Comment=${desktopString(o.comment)}`] : []),
    `Exec=sh -c ${desktopExecArgument(script)} sh %k`,
    "Terminal=false",
    "Categories=Game;",
    "",
  ].join("\n");
}

/** sh の "…" の中に書く文字（\ " $ ` の前に \ を置く）。 */
const shDoubleQuoted = (s: string): string => s.replace(/[\\"`$]/g, "\\$&");

/** .desktop の Exec の一つの引数（引用の中の \ " $ ` の前に \ を置き、文字列の決まりで \ を二つにする。% は %%。Desktop Entry の仕様）。 */
export function desktopExecArgument(arg: string): string {
  return `"${arg.replace(/[\\"`$]/g, "\\$&")}"`.replace(/\\/g, "\\\\").replace(/%/g, "%%");
}
