const translate = createTranslator(CATALOG);

/** 開発サーバーの文を英語にする（表 → 構文チェックの英語 → 原文。複数行は一行ずつ）。 */
export function englishServerText(text: string): string {
  return text
    .split("\n")
    .map((line) => translate(line) ?? translateDiagnosticText(line) ?? line)
    .join("\n");
}

/** 開発サーバーの表の訳（当てはまらなければ null。テストが使う）。 */
export function translateServerText(text: string): string | null {
  return translate(text);
}

const LANGUAGE = Symbol("liminalia.studio.language");

/** 要求の見出しから、応答の文の言語を覚える（"en" のときだけ英語にする）。 */
export function rememberLanguage(req: IncomingMessage, res: ServerResponse): void {
  (res as unknown as Record<symbol, string>)[LANGUAGE] = req.headers[STUDIO_LANGUAGE_HEADER] === "en" ? "en" : "ja";
}

/** 応答に書く断りの文（覚えた言語が英語なら英語に）。 */
export function localizedError(res: ServerResponse, message: string): string {
  return (res as unknown as Record<symbol, string>)[LANGUAGE] === "en" ? englishServerText(message) : message;
}
