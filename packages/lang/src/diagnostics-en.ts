/** 日本語の文を、表で英語にする（形が表に無ければ null）。 */
export const translateDiagnosticText = createTranslator(CATALOG);

/**
 * 診断の英語の文。プラグインの診断は書いてある訳だけを使う（無ければ原文）。エンジンの診断は、文の形から作り、形が無ければ code の一文。
 * code も知らないもの（プラグインが実行中に出す診断など）は原文のまま。ヒントは形が無ければ原文のまま（書き方の例など、訳の要らないものがある）。
 */
export function englishDiagnostic(d: Pick<Diagnostic, "code" | "message" | "messageEn" | "hint" | "hintEn" | "plugin">): { message: string; hint?: string } {
  const message = d.messageEn ?? (d.plugin ? d.message : (translateDiagnosticText(d.message) ?? DIAGNOSTIC_CODES_EN[d.code] ?? d.message));
  const hint = d.hintEn ?? d.hint;
  if (hint === undefined) return { message };
  return { message, hint: d.hintEn !== undefined || d.plugin ? hint : (translateDiagnosticText(hint) ?? hint) };
}
